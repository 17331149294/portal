package v1

import "testing"

// Regression tests: malformed UDP packets must never panic the process
// (previously AttrLen<2 would make a negative slice and panic).
func TestUnmarshallNoPanicOnMalformed(t *testing.T) {
	v := new(Version)
	cases := [][]byte{
		{0x01}, // truncated header
		{0x01, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
		// valid 16-byte header, AttrNum=1, then attribute with AttrLen=1 (<2)
		{0x01, 0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
			0xc0, 0xa8, 0x01, 0x01, 0x00, 0x00, 0x00, 0x01,
			0x03, 0x01},
		// valid header, AttrNum=1, attribute with AttrLen=255 but no data
		{0x01, 0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
			0xc0, 0xa8, 0x01, 0x01, 0x00, 0x00, 0x00, 0x01,
			0x03, 0xff},
	}
	for _, c := range cases {
		v.Unmarshall(c) // must not panic
	}
}

func TestUnmarshallValid(t *testing.T) {
	v := new(Version)
	m := v.Unmarshall([]byte{
		0x01, 0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
		0xc0, 0xa8, 0x01, 0x01, 0x00, 0x00, 0x00, 0x01, // header
		0x03, 0x12, // attr type=3, length=18 -> 16 data bytes
		0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
		0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10,
	})
	if m.AttributeLen() != 1 {
		t.Errorf("AttributeLen = %d, want 1", m.AttributeLen())
	}
	attr := m.Attribute(0)
	if attr.Type() != 0x03 {
		t.Errorf("attr type = %d, want 3", attr.Type())
	}
	if attr.Length() != 18 {
		t.Errorf("attr length = %d, want 18", attr.Length())
	}
}
